"""Baseline projection evaluation, per BUILD_SPEC.md section 7.4 / 16.4.

Methodology: a **time-ordered** backtest, never a random split. For every
veteran with all 3 NBA seasons on record (2023-24, 2024-25, 2025-26), the
two oldest seasons are fed to `baseline.project_player` as if 2025-26 had
not happened yet, and the resulting projection is compared against the
real (synthetic, in this demo dataset) 2025-26 season. This is a benchmark
against DraftCourt's own fabricated demo history, not a claim about real
NBA prediction accuracy — every report generated by this module says so
explicitly.

Players with fewer than 3 NBA seasons (rookies, anyone missing history)
have no held-out season to compare against and are excluded from the
backtest — reported as an explicit "not evaluable" count per subgroup
rather than silently dropped or faked.
"""

from __future__ import annotations

import statistics
from dataclasses import dataclass, field
from typing import Literal

from scipy import stats as scipy_stats

from app.pipelines.baseline import PlayerContext, SeasonStatLine, project_player
from app.pipelines.scoring import fantasy_points

_RATE_STATS = ("pts", "reb", "ast", "stl", "blk", "tov", "fgm", "fga", "ftm", "fta", "threePm")
LOW_MINUTES_THRESHOLD = 18.0
_MIN_CASES_FOR_CORRELATION = 2
_MIN_DISTINCT_VALUES_FOR_CORRELATION = 2

Subgroup = Literal["all", "veteran", "injured", "unsigned", "low_minutes"]


@dataclass(frozen=True)
class EvalCase:
    player_id: str
    display_name: str
    train_lines: list[SeasonStatLine]  # oldest -> newest, cutoff-excluded
    actual: SeasonStatLine  # the held-out season being predicted
    context: PlayerContext


@dataclass
class SubgroupMetrics:
    subgroup: str
    n: int
    minutes_weighted_mae: dict[str, float]
    fantasy_points_mae: float
    games_played_mae: float
    spearman_rank_correlation: float | None
    interval_coverage: float


@dataclass
class EvaluationReport:
    model_key: str
    model_version: str
    cutoff_season: str
    subgroups: list[SubgroupMetrics]
    not_evaluable_counts: dict[str, int] = field(default_factory=dict)


def _predict(case: EvalCase) -> dict[str, float]:
    line = project_player(case.player_id, case.train_lines, None, case.context)
    return line.model_dump(by_alias=True)


def _minutes_weighted_mae(
    cases: list[EvalCase], predictions: list[dict[str, float]]
) -> dict[str, float]:
    """Minutes-weighted MAE per stat (BUILD_SPEC.md section 7.4): errors
    for players who actually played heavy minutes count more than errors
    for deep-bench players, since the former matter more for fantasy
    outcomes."""
    result: dict[str, float] = {}
    for stat in _RATE_STATS:
        total_weight = 0.0
        weighted_error_sum = 0.0
        for case, prediction in zip(cases, predictions, strict=True):
            actual_per_game = case.actual.per_game()
            weight = max(case.actual.minutes_total / max(case.actual.games_played, 1), 1.0)
            weighted_error_sum += weight * abs(prediction[stat] - actual_per_game[stat])
            total_weight += weight
        result[stat] = round(weighted_error_sum / total_weight, 4) if total_weight > 0 else 0.0
    return result


def _fantasy_points_mae(cases: list[EvalCase], predictions: list[dict[str, float]]) -> float:
    errors = [
        abs(fantasy_points(prediction) - fantasy_points(case.actual.per_game()))
        for case, prediction in zip(cases, predictions, strict=True)
    ]
    return round(statistics.fmean(errors), 4) if errors else 0.0


def _games_played_mae(cases: list[EvalCase], predictions: list[dict[str, float]]) -> float:
    errors = [
        abs(prediction["games"] - case.actual.games_played)
        for case, prediction in zip(cases, predictions, strict=True)
    ]
    return round(statistics.fmean(errors), 4) if errors else 0.0


def _spearman(cases: list[EvalCase], predictions: list[dict[str, float]]) -> float | None:
    if len(cases) < _MIN_CASES_FOR_CORRELATION:
        return None
    predicted_pts = [p["pts"] for p in predictions]
    actual_pts = [case.actual.per_game()["pts"] for case in cases]
    if (
        len(set(predicted_pts)) < _MIN_DISTINCT_VALUES_FOR_CORRELATION
        or len(set(actual_pts)) < _MIN_DISTINCT_VALUES_FOR_CORRELATION
    ):
        return None
    correlation = scipy_stats.spearmanr(predicted_pts, actual_pts).statistic
    return round(float(correlation), 4)


def _interval_coverage(cases: list[EvalCase], predictions_full: list[dict[str, object]]) -> float:
    """Fraction of (case, stat) pairs where the actual per-game value fell
    within the heuristic [lower80, upper80] band — a sanity check on
    whether the *labeled heuristic* interval is at least directionally
    reasonable, not a claim of true 80% statistical calibration (see
    baseline.py's module docstring)."""
    hits = 0
    total = 0
    for case, prediction in zip(cases, predictions_full, strict=True):
        actual_per_game = case.actual.per_game()
        lower80 = prediction["lower80"]
        upper80 = prediction["upper80"]
        assert isinstance(lower80, dict)
        assert isinstance(upper80, dict)
        for stat in _RATE_STATS:
            if stat not in lower80:
                continue
            total += 1
            if lower80[stat] <= actual_per_game[stat] <= upper80[stat]:
                hits += 1
    return round(hits / total, 4) if total > 0 else 0.0


def _evaluate_subgroup(subgroup: str, cases: list[EvalCase]) -> SubgroupMetrics:
    predictions = [_predict(case) for case in cases]
    return SubgroupMetrics(
        subgroup=subgroup,
        n=len(cases),
        minutes_weighted_mae=_minutes_weighted_mae(cases, predictions),
        fantasy_points_mae=_fantasy_points_mae(cases, predictions),
        games_played_mae=_games_played_mae(cases, predictions),
        spearman_rank_correlation=_spearman(cases, predictions),
        interval_coverage=_interval_coverage(cases, predictions),  # type: ignore[arg-type]
    )


def run_evaluation(
    cases: list[EvalCase], *, model_key: str, model_version: str, cutoff_season: str
) -> EvaluationReport:
    """Pure function over pre-assembled `EvalCase`s (already time-ordered
    and cutoff-truncated by the caller — see
    services/analytics/app/pipelines/cli.py's `evaluate` command for how
    they're built from the database) — deterministic and leakage-free by
    construction, since `case.train_lines` never includes `case.actual`."""
    all_metrics = _evaluate_subgroup("all", cases)
    veteran_metrics = _evaluate_subgroup(
        "veteran", [c for c in cases if c.context.status != "INJURED"]
    )
    injured_metrics = _evaluate_subgroup(
        "injured", [c for c in cases if c.context.status == "INJURED"]
    )
    unsigned_metrics = _evaluate_subgroup("unsigned", [c for c in cases if c.context.unsigned])
    rookie_metrics = _evaluate_subgroup("rookie", [c for c in cases if c.context.rookie])
    low_minutes_cases = [
        c
        for c in cases
        if c.train_lines and c.train_lines[-1].per_game()["minutesPerGame"] < LOW_MINUTES_THRESHOLD
    ]
    low_minutes_metrics = _evaluate_subgroup("low_minutes", low_minutes_cases)

    # Rookies and (typically) unsigned players structurally never have 3
    # prior NBA seasons to hold one out from, so they are excluded from
    # `cases` upstream by construction — n=0 here is expected, not a bug.
    # Documented explicitly rather than silently omitted (see
    # models/baseline-v1/evaluation-report.md's "Evaluation limitations").
    not_evaluable = {
        "rookie": rookie_metrics.n,
        "unsigned": unsigned_metrics.n,
    }

    return EvaluationReport(
        model_key=model_key,
        model_version=model_version,
        cutoff_season=cutoff_season,
        subgroups=[
            all_metrics,
            veteran_metrics,
            injured_metrics,
            unsigned_metrics,
            rookie_metrics,
            low_minutes_metrics,
        ],
        not_evaluable_counts=not_evaluable,
    )


__all__: list[str] = [
    "LOW_MINUTES_THRESHOLD",
    "EvalCase",
    "EvaluationReport",
    "SubgroupMetrics",
    "fantasy_points",
    "run_evaluation",
]
